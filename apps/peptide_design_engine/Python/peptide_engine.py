            CONFIG["_HOTSPOT_STATUS"] = "PDB_FALLBACK_TO_DEBUG_SEQUENCE" if debug else ("PDB_FALLBACK_TO_SEQUENCE" if hs else "PDB_FALLBACK_SEQUENCE_NO_HOTSPOTS")
