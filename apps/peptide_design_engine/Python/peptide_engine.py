def base(x):
    if isinstance(x, str) and len(x) == 2 and x.startswith("d") and x[1] in AA:
        return x[1]
    return NON_NAT_MAP.get(x, x)

def is_residue(x):
    return base(x) in AA

def clean_bases(seq):
    return [base(x) for x in seq if base(x) in AA]

def to_esm_seq(seq):
    return "".join(clean_bases(seq))

